import { test } from "node:test";
import * as fs from "node:fs";
import * as path from "node:path";
import activate, { __testOnlyResetOwnerSession, __testOnlyResetStaleFlag } from "../extensions/loops/goal.js";
import { sendContinuation, resetContinuationDispatchState } from "../extensions/goal-continuation.js";
import { MockPi, makeMockCtx, seedGoal, seedState, tmpCwd, tick } from "./harness/mock-pi.js";
const GLOBAL_SETTINGS_PATH = process.env.GLLA_GLOBAL_SETTINGS_PATH!;
const pi = new MockPi();
activate(pi.api);
test("debug fences", async () => {
  const cwd = tmpCwd();
  fs.writeFileSync(GLOBAL_SETTINGS_PATH, JSON.stringify({ autoResume: true, aggressiveMode: false }));
  __testOnlyResetOwnerSession(); __testOnlyResetStaleFlag(); resetContinuationDispatchState(cwd);
  const goalId = `dbg-${Date.now()}`;
  seedState(cwd, { goal: seedGoal({ id: goalId, status: "active", policy: "goal", autoResumedAt: new Date().toISOString(), autoResumedEvent: "dbg" }) });
  const ctx = makeMockCtx(cwd, { sessionManager: { name: "dbg" } });
  await pi.fire("session_start", { reason: "reload" }, ctx);
  await tick(150);
  sendContinuation(goalId);
  await tick(300);
  const raw = fs.readFileSync(path.join(cwd, ".pi-glla", "active.jsonl"), "utf8");
  const types = raw.trim().split("\n").filter(Boolean).map((l) => { try { return JSON.parse(l).type; } catch { return "?"; } });
  console.log("SENT:", pi.sent.length, "LEDGER-TAIL:", JSON.stringify(types.slice(-8)));
  await pi.fire("session_shutdown", { reason: "test-end" }, ctx);
});
